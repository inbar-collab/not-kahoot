/** "Question 3 of 25", or the practice label. The practice round is not numbered. */
export function roundLabel(s: Strings, index: number, game: Pick<PublicGame, "totalRounds" | "practiceRounds">): string {
  if (index < game.practiceRounds) return s.practiceLabel;
  return s.questionOf(index + 1 - game.practiceRounds, game.totalRounds - game.practiceRounds);
}

