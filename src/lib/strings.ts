export function getStrings(ctx: StringsContext | null | undefined = {}): Strings {
  return ctx?.locale === "en" ? en(ctx ?? {}) : he(ctx ?? {});
}

/** Picks one line from a list, the same one on every screen for a given seed. */
export function pick<T>(list: readonly T[], seed: number): T {
  return list[Math.abs(Math.trunc(seed)) % list.length];
}

